    double base = Double.parseDouble(CampoNota1.getText());
    double altura = Double.parseDouble(CampoNota2.getText());
    double apotema = Double.parseDouble(CampoNota3.getText());

    Piramide piramide = new Piramide(base, altura, apotema);

    volumen.setText(String.format(
        "Volumen: %.2f cm3", piramide.getVolumen()
    ));

