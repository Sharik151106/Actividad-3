    private void calcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calcularActionPerformed
if (campoNota1.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Debes ingresar la nota 1.");
    return;
}

if (campoNota2.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Debes ingresar la nota2.");
    return;
}

if (campoNota3.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Debes ingresar la nota 3.");
    return;
}

if (campoNota4.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Debes ingresar la nota 4.");
    return;
}

if (campoNota5.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Debes ingresar la nota 5.");
    return;
}

try {
    Notas notas = new Notas();

    notas.listaNotas[0] = Double.parseDouble(campoNota1.getText());
    notas.listaNotas[1] = Double.parseDouble(campoNota2.getText());
    notas.listaNotas[2] = Double.parseDouble(campoNota3.getText());
    notas.listaNotas[3] = Double.parseDouble(campoNota4.getText());
    notas.listaNotas[4] = Double.parseDouble(campoNota5.getText());

    notas.calcularPromedio();
    notas.calcularDesviación();

    promedio.setText("Promedio = " +
            String.format("%.2f", notas.calcularPromedio()));

    double desv = notas.calcularDesviación();
    desviacion.setText("Desviación estándar = " +
            String.format("%.2f", desv));

    mayor.setText("Valor mayor = " +
            String.valueOf(notas.calcularMayor()));

    menor.setText("Valor menor = " +
            String.valueOf(notas.calcularMenor()));
    

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Debes ingresar valores númericos en las cinco notas.");
}

    }//GEN-LAST:event_calcularActionPerformed

